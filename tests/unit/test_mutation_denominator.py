def test_a_crash_written_over_a_real_verdict_is_recovered_end_to_end(
    real_mutmut_run: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """THE WHOLE EXERCISE, IN ONE TEST, ON REAL MUTMUT OUTPUT.

    Take a mutant mutmut reached a verdict on, overwrite that verdict with a
    segfault — the exact corruption F-007 describes — and run the CLI with
    `--resolve`. The out-of-fork re-run must recover the verdict mutmut
    originally had, and the CLI must then certify the denominator complete.

    The oracle tree is COPIED first: mutating the session fixture would leave
    every later test reading a result this test invented.
    """
    copied = tmp_path / "mutants"
    shutil.copytree(real_mutmut_run, copied)
    meta = next(copied.rglob("*.py.meta"))
    recorded = json.loads(meta.read_text(encoding="utf-8"))
    victim = next(name for name, code in recorded["exit_code_by_key"].items() if code is not None)
    original_verdict = md.status_for(recorded["exit_code_by_key"][victim])[0]
    recorded["exit_code_by_key"][victim] = -11
    meta.write_text(json.dumps(recorded), encoding="utf-8")

    assert any(m.status == "segfault" for m in md.read_mutants(copied)), (
        "precondition: the corruption must be visible before it is repaired"
    )

    corrupted = md.read_mutants(copied)
    resolutions = md.resolve(
        md.without_verdict(corrupted),
        md.read_covering_tests(copied),
        copied,
        lambda mutant, tests: md.run_covering_tests(mutant, tests, copied),
    )

    # BIT FOR BIT. Not "close to", not "also has a verdict" — the recovered
    # table must be the table that existed before the crash was written over it.
    assert md.tally_by_source(md.with_resolutions(corrupted, resolutions)) == md.tally_by_source(
        md.read_mutants(real_mutmut_run)
    )
    assert [resolution.verdict for resolution in resolutions] == [original_verdict]

    code = md.cli(["mutation_denominator.py", "--resolve", "--mutants-dir", str(copied)])

    printed = capsys.readouterr().out
    assert code == 0, printed
    assert "still no verdict after resolution: 0" in printed
    assert "every one of 4 mutants has a verdict" in printed


