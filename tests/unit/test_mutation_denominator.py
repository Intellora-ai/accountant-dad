#: The fixture below writes four mutants: one killed, one survived, one
#: segfaulted, one never run. Named so the assertions read as claims about the
#: fixture rather than as bare integers.
FOUR_MUTANTS = 4
TWO_WITH_NO_VERDICT = 2

#: An exit code mutmut has no entry for, used to prove an unknown status is
#: reported with its number instead of silently becoming `suspicious`.
UNMAPPED_EXIT_CODE = 66

#: pytest's usage-error exit code. Not a verdict about any mutant.
PYTEST_USAGE_ERROR = 4

# ═══════════════════════════════════════════════════════════════════════════
# A mutation copy, built by hand. Real files, real JSON — nothing is patched.
# ═══════════════════════════════════════════════════════════════════════════

#: The generated file's shape, reduced to the one line that matters here: the
#: registration that tells the trampoline a mutant exists. Copied in structure
#: from a real `mutants/src/probe/calc.py`, and proven to match by
#: `test_registration_scan_reads_a_file_mutmut_actually_generated`.
_REGISTRATION_TEMPLATE = "mutants_{function}__mutmut['{name}'] = {name}  # type: ignore\n"


def _write_mutation_copy(
    root: Path,
    source: str,
    exit_code_by_key: dict[str, int | None],
    *,
    register: Sequence[str] | None = None,
) -> Path:
    """Write a `mutants/` tree recording `exit_code_by_key` for `source`.

    `register` names the mutants the generated file claims to define; it
    defaults to all of them, so the deliberately-stale case has to be asked for.
    """
    mutants_dir = root / "mutants"
    generated = mutants_dir / source
    generated.parent.mkdir(parents=True, exist_ok=True)
    names = list(exit_code_by_key) if register is None else list(register)
    generated.write_text(
        "".join(
            _REGISTRATION_TEMPLATE.format(
                function=md.mangled_name(name).rpartition(".")[2], name=md.generated_function(name)
            )
            for name in names
        ),
        encoding="utf-8",
    )
    meta = generated.with_suffix(generated.suffix + ".meta")
    meta.write_text(
        json.dumps(
            {
                "exit_code_by_key": exit_code_by_key,
                "hash_by_function_name": {},
                "type_check_error_by_key": {},
                "durations_by_key": {},
                "estimated_durations_by_key": {},
            }
        ),
        encoding="utf-8",
    )
    return mutants_dir


def _write_stats(mutants_dir: Path, tests_by_function: dict[str, list[str]]) -> None:
    (mutants_dir / md.STATS_FILENAME).write_text(
        json.dumps({"tests_by_mangled_function_name": tests_by_function}), encoding="utf-8"
    )


#: One killed, one survived, one segfaulted, one never run. The segfault and the
#: never-run mutant are the population the mutation score silently drops.
_FOUR_OUTCOMES = {
    "probe.calc.x_add__mutmut_1": 1,
    "probe.calc.x_add__mutmut_2": 0,
    "probe.calc.x_add__mutmut_3": -11,
    "probe.calc.x_add__mutmut_4": None,
}


# ═══════════════════════════════════════════════════════════════════════════
# The denominator. Everything mutmut generated, whatever became of it.
# ═══════════════════════════════════════════════════════════════════════════


def test_a_segfaulted_and_an_unrun_mutant_stay_in_the_denominator(tmp_path: Path) -> None:
    """THE DEFECT, stated as an assertion (F-007).

    `killed + survived` is 2 here and the tree contains 4. A tool that agreed
    with the gate would report 2 and this repository would keep believing a
    score taken over half its mutants.
    """
    mutants_dir = _write_mutation_copy(tmp_path, "src/probe/calc.py", dict(_FOUR_OUTCOMES))

    mutants = md.read_mutants(mutants_dir)

    assert len(mutants) == FOUR_MUTANTS, "the denominator is every mutant, not the scoreable ones"
    assert {mutant.status for mutant in mutants} == {
        "killed",
        "survived",
        "segfault",
        "not checked",
    }


def test_every_mutant_with_no_verdict_is_named_not_just_counted(tmp_path: Path) -> None:
    """A count says the measurement shrank. A name says which line stopped being
    measured, and only the second is actionable.
    """
    mutants_dir = _write_mutation_copy(tmp_path, "src/probe/calc.py", dict(_FOUR_OUTCOMES))

    silent = md.without_verdict(md.read_mutants(mutants_dir))

    assert [mutant.name for mutant in silent] == [
        "probe.calc.x_add__mutmut_3",
        "probe.calc.x_add__mutmut_4",
    ]
    printed = "\n".join(md.report(md.read_mutants(mutants_dir)))
    assert "probe.calc.x_add__mutmut_3" in printed
    assert "probe.calc.x_add__mutmut_4" in printed
    assert "segfault" in printed


def test_the_tally_itemises_the_excluded_bucket_by_status(tmp_path: Path) -> None:
    """`4 not scoreable` is a number to argue with. `segfault=1, not checked=1`
    is a diagnosis, and the two failures have completely different fixes.
    """
    mutants_dir = _write_mutation_copy(tmp_path, "src/probe/calc.py", dict(_FOUR_OUTCOMES))

    (tally,) = md.tally_by_source(md.read_mutants(mutants_dir))

    assert tally.source == "src/probe/calc.py"
    assert (tally.generated, tally.killed, tally.survived) == (FOUR_MUTANTS, 1, 1)
    assert tally.no_verdict == {"segfault": 1, "not checked": 1}
    assert tally.no_verdict_total == TWO_WITH_NO_VERDICT


def test_two_source_files_are_tallied_separately(tmp_path: Path) -> None:
    """A per-file report is the whole request. One combined row would hide a
    single module that segfaults entirely inside a healthy total.
    """
    _write_mutation_copy(tmp_path, "src/probe/calc.py", {"probe.calc.x_add__mutmut_1": 1})
    mutants_dir = _write_mutation_copy(
        tmp_path, "src/probe/other.py", {"probe.other.x_f__mutmut_1": -11}
    )

    tallies = md.tally_by_source(md.read_mutants(mutants_dir))

    assert [(t.source, t.generated, t.no_verdict_total) for t in tallies] == [
        ("src/probe/calc.py", 1, 0),
        ("src/probe/other.py", 1, 1),
    ]


def test_an_exit_code_mutmut_has_never_seen_is_reported_with_its_number(tmp_path: Path) -> None:
    """mutmut's status table is a `defaultdict` returning `suspicious`, so a new
    exit code arrives wearing an old name. This keeps the number attached.
    """
    mutants_dir = _write_mutation_copy(
        tmp_path, "src/probe/calc.py", {"probe.calc.x_a__mutmut_1": UNMAPPED_EXIT_CODE}
    )

    (mutant,) = md.read_mutants(mutants_dir)

    assert mutant.status == "suspicious"
    assert mutant.status_was_defaulted is True
    assert "66" in mutant.describe()
    assert "UNKNOWN TO MUTMUT" in mutant.describe()


def test_asking_about_an_unknown_exit_code_does_not_grow_mutmuts_table() -> None:
    """A `defaultdict` INSERTS on a missing lookup. Reading it with `[]` would
    make this module quietly rewrite the tool it is measuring, and the second
    read of the same code would then claim mutmut had always known it.
    """
    never_used = 4242
    assert never_used not in status_by_exit_code, "precondition: a code mutmut has no entry for"

    status, defaulted = md.status_for(never_used)

    assert (status, defaulted) == ("suspicious", True)
    assert never_used not in status_by_exit_code, "reading the table must not extend it"


def test_a_known_exit_code_is_not_reported_as_a_guess() -> None:
    """The other direction. Without it, a function that always answered
    "defaulted" would pass the test above and label every real status a guess.
    """
    assert md.status_for(1) == ("killed", False)
    assert md.status_for(0) == ("survived", False)
    assert md.status_for(-11) == ("segfault", False)
    assert md.status_for(None) == ("not checked", False)


