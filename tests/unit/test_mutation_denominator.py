def _mutant(name: str = "probe.calc.x_add__mutmut_3", status: str = "segfault") -> md.Mutant:
    return md.Mutant(
        name=name,
        source="src/probe/calc.py",
        exit_code=-11,
        status=status,
        status_was_defaulted=False,
    )


def _copy_registering(tmp_path: Path, *names: str) -> Path:
    return _write_mutation_copy(
        tmp_path, "src/probe/calc.py", dict.fromkeys(names, -11), register=names
    )


def test_a_no_verdict_mutant_whose_tests_fail_out_of_the_fork_is_killed(tmp_path: Path) -> None:
    mutants_dir = _copy_registering(tmp_path, "probe.calc.x_add__mutmut_3")

    (resolution,) = md.resolve(
        [_mutant()],
        {"probe.calc.x_add": ("tests/test_calc.py::test_add",)},
        mutants_dir,
        lambda _mutant, _tests: 1,
    )

    assert (resolution.verdict, resolution.resolved) == ("killed", True)
    assert resolution.test_count == 1


def test_a_no_verdict_mutant_whose_tests_pass_out_of_the_fork_is_a_true_survivor(
    tmp_path: Path,
) -> None:
    """The half that matters most. These are the mutants reported as no-verdict
    that are in fact ALIVE — a real hole in the suite, hidden by a crash.
    """
    mutants_dir = _copy_registering(tmp_path, "probe.calc.x_add__mutmut_3")

    (resolution,) = md.resolve(
        [_mutant()],
        {"probe.calc.x_add": ("tests/test_calc.py::test_add",)},
        mutants_dir,
        lambda _mutant, _tests: 0,
    )

    assert (resolution.verdict, resolution.resolved) == ("survived", True)


def test_a_mutant_the_mutation_copy_does_not_register_is_never_called_a_survivor(
    tmp_path: Path,
) -> None:
    """THE FALSE SURVIVOR, TRAPPED. The trampoline calls the ORIGINAL function
    for a name it does not know, so the tests pass, pytest exits 0, and an
    unguarded resolver reads that as "alive". Measured on a real mutation copy
    before this guard existed: `probe.calc.x_add__mutmut_9999` resolved to
    `survived`.

    The runner here would answer 0 — "everything passed". The guard must reach
    its verdict without ever asking it.
    """
    mutants_dir = _copy_registering(tmp_path, "probe.calc.x_add__mutmut_1")
    asked: list[str] = []

    def runner(mutant: md.Mutant, _tests: Sequence[str]) -> int:
        asked.append(mutant.name)
        return 0

    (resolution,) = md.resolve(
        [_mutant(name="probe.calc.x_add__mutmut_9999")],
        {"probe.calc.x_add": ("tests/test_calc.py::test_add",)},
        mutants_dir,
        runner,
    )

    assert resolution.verdict == "not in mutation copy"
    assert resolution.resolved is False
    assert "ORIGINAL function" in resolution.reason
    assert asked == [], "a mutant that cannot be activated must not be run at all"


def test_a_mutant_with_no_covering_test_is_reported_and_not_guessed_at(tmp_path: Path) -> None:
    """ "No test failed" and "no test ran" are the same exit code and opposite
    facts. Calling the second one `survived` would invent a verdict (Law 24).
    """
    mutants_dir = _copy_registering(tmp_path, "probe.calc.x_add__mutmut_3")

    (resolution,) = md.resolve([_mutant()], {}, mutants_dir, lambda _mutant, _tests: 0)

    assert resolution.verdict == "no tests"
    assert resolution.resolved is False
    assert resolution.exit_code is None
    assert "no test covering" in resolution.reason


def test_an_exit_code_that_is_not_a_verdict_stays_unresolved_and_names_the_number(
    tmp_path: Path,
) -> None:
    """pytest exits 4 on a usage error and 2 on an interrupt. Neither means the
    mutant lived or died, and folding either into a column would be a guess.
    """
    mutants_dir = _copy_registering(tmp_path, "probe.calc.x_add__mutmut_3")

