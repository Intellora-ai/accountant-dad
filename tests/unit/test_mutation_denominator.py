"""The denominator tool, and the two ways it could lie.

WHAT IS BEING GUARDED. `tools/ci/mutation_denominator.py` answers one question:
how many mutants exist, and which of them never reached a verdict. Two failures
would make it worse than nothing, and both are attacked here rather than
assumed away:

    a mutant quietly leaves the count       -> the denominator is a subset again
    a mutant is called `survived` when the
    mutation copy never ran it              -> a fabricated survivor

THE ORACLE IS MUTMUT ITSELF. A resolver checked only against its own reasoning
is unproven, so the falsification half runs a REAL `mutmut run` over a
four-mutant project and then asks the resolver to re-derive the verdicts mutmut
already reached. mutmut says two are killed and two survived; the resolver must
say the same, out of the fork, from nothing but the environment variable. Both
directions matter and each alone proves nothing: a resolver that always answered
`killed` would pass the killed half, and a resolver that never activated the
mutant at all would pass the survived half.

WHY THAT IS NOT A MOCK (§J.6). The mutation copy is generated by mutmut, the
tests are run by pytest in a real subprocess, and the verdicts are compared
against mutmut's own meta store. The only thing this file constructs by hand is
the four-line project under test.

IT NEVER SKIPS. If mutmut cannot run, this file fails. A skip here would be the
exact silent exclusion the tool exists to end.
"""

