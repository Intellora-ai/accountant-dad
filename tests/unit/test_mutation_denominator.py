# ═══════════════════════════════════════════════════════════════════════════
# FALSIFICATION. A real mutmut run is the oracle; the resolver must match it.
# ═══════════════════════════════════════════════════════════════════════════

_PROJECT = "[tool.pytest.ini_options]\ntestpaths = ['tests']\npythonpath = ['src']\n"
_MUTMUT_CONFIG = "[tool.mutmut]\nsource_paths = ['src']\nalso_copy = ['pyproject.toml']\n"
#: `add` is fully caught; `clamp`'s boundary mutants are not. Chosen so a real
#: run yields BOTH verdicts — an oracle that only ever said `killed` would let a
#: resolver that always answered `killed` through.
_CALC = (
    "def add(a, b):\n    return a + b\n\n\n"
    "def clamp(x):\n    if x > 0:\n        return x\n    return 0\n"
)
_CALC_TESTS = (
    "from probe.calc import add, clamp\n\n\n"
    "def test_add():\n    assert add(1, 2) == 3\n\n\n"
    "def test_clamp():\n    assert clamp(5) == 5\n    assert clamp(-1) == 0\n"
)


def _mutmut_environment() -> dict[str, str]:
    """A clean environment for a nested mutmut run.

    `MUTANT_UNDER_TEST` is removed because this file itself runs under mutation:
    inheriting `stats` or a live mutant name would make the nested run measure
    the outer run's state. `no_proxy` is set for the reason the whole exercise
    exists — `getproxies_macosx_sysconf()` is not fork-safe, and mutmut forks.
    """
    environment = {key: value for key, value in os.environ.items() if key != md.MUTANT_ENV_VAR}
    environment.update(md.NO_PROXY_ENVIRONMENT)
    return environment


@pytest.fixture(scope="session")
def real_mutmut_run(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A genuine `mutmut run` over four mutants. Returns its `mutants/` directory.

    Session-scoped because the run costs a real process; every test below reads
    the same result, exactly as a human would read one run's output.
    """
    project = tmp_path_factory.mktemp("mutmut_oracle")
    (project / "pyproject.toml").write_text(_PROJECT + "\n" + _MUTMUT_CONFIG, encoding="utf-8")
    (project / "src" / "probe").mkdir(parents=True)
    (project / "src" / "probe" / "__init__.py").write_text("", encoding="utf-8")
    (project / "src" / "probe" / "calc.py").write_text(_CALC, encoding="utf-8")
    (project / "tests").mkdir()
    (project / "tests" / "test_calc.py").write_text(_CALC_TESTS, encoding="utf-8")

    completed = subprocess.run(  # noqa: S603 - argv list, no shell, interpreter is sys.executable
        [sys.executable, "-m", "mutmut", "run"],
        check=False,
        cwd=project,
        env=_mutmut_environment(),
        capture_output=True,
        text=True,
    )
    # NEVER a skip. A resolver whose oracle did not run is a resolver nothing
    # checked, and reporting that as "passed" is this repository's own F-029.
    assert completed.returncode == 0, (
        "the oracle `mutmut run` failed, so nothing below proves anything:\n"
        f"{completed.stdout[-4000:]}\n{completed.stderr[-4000:]}"
    )
    return project / "mutants"


def test_the_oracle_produced_both_verdicts(real_mutmut_run: Path) -> None:
    """PRECONDITION for the two tests below, asserted rather than assumed.

    If this project ever stopped producing both a killed and a surviving mutant,
    the agreement tests would still pass while checking only one direction.
    """
    statuses = {mutant.name: mutant.status for mutant in md.read_mutants(real_mutmut_run)}

    assert sorted(statuses.values()).count("killed") >= 1
    assert sorted(statuses.values()).count("survived") >= 1
    assert len(statuses) == FOUR_MUTANTS, f"expected four mutants here, got {statuses}"


def test_the_resolver_reaches_mutmuts_own_verdict_on_every_mutant(real_mutmut_run: Path) -> None:
    """THE FALSIFICATION. Known answers, both directions, from an independent
    oracle — mutmut's forked child — re-derived by an `exec`'d subprocess that
    shares none of the fork's state.

    A resolver that never activated the mutant would report every one of these
    as `survived` and fail on the killed ones. A resolver that broke the test
    run would report every one as `killed` and fail on the survivors. Only a
    resolver that actually activates the right mutant passes both.
    """
    covering = md.read_covering_tests(real_mutmut_run)
    disagreements: list[str] = []

    for mutant in md.read_mutants(real_mutmut_run):
        tests = covering[md.mangled_name(mutant.name)]
        exit_code = md.run_covering_tests(mutant, tests, real_mutmut_run)
        verdict, _ = md.verdict_from_exit_code(exit_code)
        if verdict != mutant.status:
            disagreements.append(f"{mutant.name}: mutmut={mutant.status} resolver={verdict}")

    assert disagreements == [], "the out-of-fork resolver contradicted mutmut:\n" + "\n".join(
        disagreements
    )


def test_the_resolver_reads_the_instrumented_tree_and_not_the_pristine_one(
    real_mutmut_run: Path,
) -> None:
    """The sharpest single check in this file.

    With NO mutant active every test passes. With mutmut's own killed mutant
    active the same command must fail. If `run_covering_tests` were reaching the
    authored `src/` instead of `mutants/src/`, both runs would pass — and every
    resolved mutant in this repository would be a fabricated survivor.
    """
    mutants = md.read_mutants(real_mutmut_run)
    covering = md.read_covering_tests(real_mutmut_run)
    killed = next(mutant for mutant in mutants if mutant.status == "killed")
    tests = covering[md.mangled_name(killed.name)]

    inactive = md.Mutant(
        name=killed.name.rpartition(md.MUTANT_INDEX_SEPARATOR)[0] + md.MUTANT_INDEX_SEPARATOR + "0",
        source=killed.source,
        exit_code=None,
        status="not checked",
        status_was_defaulted=False,
    )

    assert md.run_covering_tests(inactive, tests, real_mutmut_run) == md.PYTEST_ALL_PASSED
    assert md.run_covering_tests(killed, tests, real_mutmut_run) == md.PYTEST_TESTS_FAILED


