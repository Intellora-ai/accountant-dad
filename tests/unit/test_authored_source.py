# ═══════════════════════════════════════════════════════════════════════════
# The validator.
# ═══════════════════════════════════════════════════════════════════════════

PROCESS_RELATIVE_READERS = frozenset(
    {"getsource", "getfile", "getsourcefile", "getsourcelines", "findsource"}
)

# The canary feeds the validator one of each banned spelling: `inspect.
# getsource`, `inspect.getfile`, a `__file__` read next to its use, and a
# `__file__` handed to a helper — the indirection that defeated the first
# version of this guard. The canary also contains one LEGAL `__file__`
# assignment, which must NOT be counted.
BANNED_SPELLINGS_IN_THE_CANARY = 4

# A floor, not the count — new test files are expected. Its only job is to fail
# when the walk finds nothing, because a scan over an empty list passes.
FEWEST_TEST_FILES_THAT_CAN_BE_REAL = 40


def _reads_a_module_file_attribute(node: ast.AST) -> TypeGuard[ast.Attribute]:
    """Any READ of `<something>.__file__`.

    Deliberately wider than "a `__file__` that is immediately read from". The
    first version of this validator banned only `Path(x.__file__).read_text()`
    and was defeated the same afternoon by

        def top_level_imports(module_path: str) -> set[str]:
            source = pathlib.Path(module_path).read_text(...)
        ...
        imported = top_level_imports(reader.__file__)

    — the `__file__` and the read sat in different functions, so no
    single-expression rule could connect them, and `test_the_reader_imports_
    only_the_approved_stack` went on reading instrumented source. It reported
    `os`, `mutmut` and `inspect` as imports of `reader.py`.

    Chasing that across function boundaries needs dataflow analysis. Banning
    the attribute needs none, and there is nothing to lose by banning it:
    `authored_path` and `running_path` cover every legitimate use between
    them, and which one a caller wants is exactly the decision that must be
    made deliberately.

    Bare `__file__` — the test file's own — is an `ast.Name`, not an
    attribute, and stays legal. Assigning `module.__file__` on a constructed
    module is a `Store`, not a read, and stays legal.
    """
    return (
        isinstance(node, ast.Attribute)
        and node.attr == "__file__"
        and isinstance(node.ctx, ast.Load)
    )


def _test_files() -> list[pathlib.Path]:
    root = pathlib.Path(__file__).resolve().parent.parent
    return sorted(root.rglob("*.py"))


def test_no_test_reads_source_through_the_running_interpreter() -> None:
    """THE VALIDATOR. Every source read goes through `authored_source`.

    `inspect.getsource`, its siblings, and `<module>.__file__` all answer
    "what is loaded", never "what is written". Under mutation the loaded
    module is a rewrite, so a whitelist
    assertion turns red on mutmut's own code and a function-level assertion
    turns green against mutmut's boilerplate. Neither outcome is about this
    repository.
    """
    offenders: list[str] = []
    for path in _test_files():
        text = path.read_text(encoding="utf-8")
        for node in ast.walk(ast.parse(text)):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in PROCESS_RELATIVE_READERS
            ):
                offenders.append(f"{path.name}:{node.lineno} inspect.{node.func.attr}(...)")
            elif _reads_a_module_file_attribute(node):
                offenders.append(f"{path.name}:{node.lineno} <module>.__file__")
    assert offenders == [], (
        "these read source through the running interpreter. Use "
        "`authored_source`/`authored_path` to assert about what we WROTE, or "
        "`running_path` to execute or inspect what is LOADED — but say which:\n  "
        + "\n  ".join(sorted(offenders))
    )


def test_the_validator_would_catch_the_pattern_it_bans() -> None:
    """HOLLOW-GATE DEFENCE. A validator that scans nothing exits 0 too.

    Feeds it both banned spellings and requires both to be seen. Without this,
    a typo in the attribute set would leave the guard reporting green forever.
    """
    banned = ast.parse(
        "import inspect, pathlib\n"
        "a = inspect.getsource(m)\n"
        "b = inspect.getfile(m)\n"
        "c = pathlib.Path(m.__file__).read_text()\n"
        "d = helper(m.__file__)\n"
        "m.__file__ = legal\n"
    )
    seen = [
        node
        for node in ast.walk(banned)
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr in PROCESS_RELATIVE_READERS
        )
        or _reads_a_module_file_attribute(node)
    ]
    assert len(seen) == BANNED_SPELLINGS_IN_THE_CANARY, (
        f"the validator missed a banned spelling; saw {len(seen)} of "
        f"{BANNED_SPELLINGS_IN_THE_CANARY}"
    )


def test_the_validator_looks_at_every_test_file() -> None:
    """A scan over an empty list passes. Pin the floor to the real count."""
    files = _test_files()
    assert len(files) >= FEWEST_TEST_FILES_THAT_CAN_BE_REAL, (
        f"only {len(files)} test files found; the walk is wrong"
    )
    assert pathlib.Path(__file__).resolve() in files


def test_no_test_derives_the_source_tree_from_its_own_location() -> None:
    """THE THIRD SPELLING. Banning `inspect.getsource` and `<module>.__file__`
    left one route open, and it cost a whole mutation run at `4fc7187`:

        REPO = pathlib.Path(__file__).resolve().parents[2]
        PACKAGE = REPO / "src" / "accountant_dad"

    No module object, no `inspect` call — just the test file asking where it
    is. Under mutation the test file itself lives in `mutants/`, so `PACKAGE`
    walks the instrumented copies.

    It survived because the two trees agreed on everything the reader asked.
    mutmut 3.7.0 ended that: its dispatcher imports `mutmut` at module scope,
    so `test_declared_dependencies` reported thirty-three modules "needing"
    mutmut, failed the stats phase, and left all 4097 mutants unscored.

    Bare `__file__` stays legal — a test locating its own fixtures is right to
    use it. Deriving the SOURCE TREE from it is what is banned; use
    `authored_repo_root()`.
    """
    offenders: list[str] = []
    for path in _test_files():
        tree = ast.parse(path.read_text(encoding="utf-8"))
        rooted_in_own_location = {
            target.id
            for node in tree.body
            if isinstance(node, ast.Assign) and "__file__" in ast.unparse(node.value)
            for target in node.targets
            if isinstance(target, ast.Name)
        }
        if not rooted_in_own_location:
            continue
        for node in ast.walk(tree):
            if not (isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div)):
                continue
            joined = ast.unparse(node)
            reaches_source = '"src"' in joined or "'src'" in joined
            if reaches_source and any(name in joined for name in rooted_in_own_location):
                # `A / "src" / "pkg"` is two nested BinOps and would report
                # the same line twice. A duplicated finding reads as two
                # defects and makes the count meaningless.
                finding = f"{path.name}:{node.lineno}"
                if not any(o.startswith(finding) for o in offenders):
                    offenders.append(f"{finding} {joined[:70]}")
    assert offenders == [], (
        "these derive the source tree from the test file's own location, which "
        "points into `mutants/` under mutation. Use `authored_repo_root()`:\n  "
        + "\n  ".join(sorted(offenders))
    )


def test_the_third_spelling_validator_catches_what_it_bans() -> None:
    """HOLLOW-GATE DEFENCE, both directions.

    The banned shape must be seen, and the legal one must NOT be — a validator
    that flags every `__file__` would be rejected on sight and quietly deleted.
    """
    banned = ast.parse(
        "import pathlib\n"
        "REPO = pathlib.Path(__file__).resolve().parents[2]\n"
        "PACKAGE = REPO / 'src' / 'accountant_dad'\n"
    )
    legal = ast.parse(
        "import pathlib\n"
        "HERE = pathlib.Path(__file__).parent\n"
        "FIXTURE = HERE / 'fixtures' / 'invoice.pdf'\n"
    )

    def offences(tree: ast.Module) -> int:
        roots = {
            t.id
            for n in tree.body
            if isinstance(n, ast.Assign) and "__file__" in ast.unparse(n.value)
            for t in n.targets
            if isinstance(t, ast.Name)
        }
        return len(
            {
                n.lineno
                for n in ast.walk(tree)
                if isinstance(n, ast.BinOp)
                and isinstance(n.op, ast.Div)
                and ("'src'" in ast.unparse(n) or '"src"' in ast.unparse(n))
                and any(r in ast.unparse(n) for r in roots)
            }
        )

    assert offences(banned) == 1, "the validator misses the shape that broke the mutation run"
    assert offences(legal) == 0, "the validator flags a test locating its own fixtures"
