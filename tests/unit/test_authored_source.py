def test_a_file_outside_a_mutation_copy_is_returned_unchanged(tmp_path: pathlib.Path) -> None:
    """No `mutants` component means nothing to undo."""
    authored = tmp_path / "src" / "plain.py"
    authored.parent.mkdir(parents=True)
    authored.write_text(AUTHORED_BODY, encoding="utf-8")
    assert authored_path(_module_from(authored)) == authored.resolve()


def test_a_directory_named_mutants_with_no_twin_is_left_alone(tmp_path: pathlib.Path) -> None:
    """The redirect is conditional on the authored file EXISTING.

    A repository that genuinely keeps a directory called `mutants` is not a
    mutation copy, and stripping it would point at nothing. Guards the
    dangerous direction: silently reading the wrong file.
    """
    only = tmp_path / "mutants" / "real.py"
    only.parent.mkdir(parents=True)
    only.write_text(AUTHORED_BODY, encoding="utf-8")
    assert authored_path(_module_from(only)) == only.resolve()


def test_a_module_whose_file_is_gone_fails_loudly(tmp_path: pathlib.Path) -> None:
    """Never a silent fallback to whatever the interpreter happens to hold."""
    missing = tmp_path / "src" / "vanished.py"
    with pytest.raises(AuthoredSourceUnavailableError, match="not a file"):
        authored_path(_module_from(missing))


def test_the_parse_tree_comes_from_the_authored_text(tmp_path: pathlib.Path) -> None:
    """`authored_tree` is the parse of `authored_source`, not of the import."""
    authored = tmp_path / "src" / "pkg" / "t.py"
    authored.parent.mkdir(parents=True)
    authored.write_text(AUTHORED_BODY, encoding="utf-8")
    instrumented = tmp_path / "mutants" / "src" / "pkg" / "t.py"
    instrumented.parent.mkdir(parents=True)
    instrumented.write_text(AUTHORED_BODY + MUTMUT_DISPATCHER, encoding="utf-8")

    names = {
        node.name
        for node in authored_tree(_module_from(instrumented)).body
        if isinstance(node, ast.FunctionDef)
    }
    assert names == {"combine", "helper"}, f"parsed the wrong file: {sorted(names)}"


