"""Source-reading discipline: a test may only assert about AUTHORED source.

Two things live here, and they are two halves of one guard.

The first half tests `tools/ci/authored_source.py` itself — including a
reproduction of the exact failure that killed the `mutation` gate on
`a501a69`, built from mutmut's real dispatcher text rather than a paraphrase
of it.

The second half is the validator: an AST scan over every file under `tests/`
that refuses `inspect.getsource` and its four siblings, and refuses reading a
module's file through its own `__file__`. Both forms answer *"what is this
interpreter running"* when the question asked was *"what did we write"*. Under
mutation those differ, and the difference has now cost two separate gate
failures — one loud, one silent.

WHY A VALIDATOR AND NOT A FIX. The five instances found so far were each found
by a CI job that takes 3h21m when it succeeds, one at a time, months apart.
The class cannot be policed by remembering it. It can be policed by a test that
runs in milliseconds and names the file and line.
"""

from __future__ import annotations

import ast
import pathlib
from types import ModuleType
from typing import TypeGuard

import pytest
from authored_source import (
    AuthoredSourceUnavailableError,
    authored_function_source,
    authored_path,
    authored_source,
    authored_tree,
)

from accountant_dad.engines.input_engine import assembly as assembly_module

# ═══════════════════════════════════════════════════════════════════════════
# mutmut's real dispatcher, copied character for character out of
# `mutants/src/accountant_dad/engines/input_engine/assembly.py` as generated by
# mutmut 3.3.1. Written out rather than referenced so this test keeps failing
# for the right reason on a machine where mutation cannot run at all (F-016).
# ═══════════════════════════════════════════════════════════════════════════
MUTMUT_DISPATCHER = '''
def _mutmut_trampoline(orig, mutants, call_args, call_kwargs, self_arg = None):
    """Forward call to original or mutated function, depending on the environment"""
    import os
    mutant_under_test = os.environ['MUTANT_UNDER_TEST']
    if mutant_under_test == 'fail':
        from mutmut.__main__ import MutmutProgrammaticFailException
        raise MutmutProgrammaticFailException('Failed programmatically')
    elif mutant_under_test == 'stats':
        from mutmut.__main__ import record_trampoline_hit
        record_trampoline_hit(orig.__module__ + '.' + orig.__name__)
        result = orig(*call_args, **call_kwargs)
        return result
'''

AUTHORED_BODY = '''\
"""The authored module."""


def combine(left: object | None, right: object | None) -> list[object]:
    """Compares against None and nothing else."""
    return [value for value in (left, right) if value is not None]


def helper() -> int:
    def combine() -> int:
        return 1

    return combine()
'''


def _module_from(path: pathlib.Path) -> ModuleType:
    """A real module object claiming to come from `path`.

    A duck-typed stand-in does not work: `inspect.getfile` rejects anything
    that is not genuinely a module, class, method, function, traceback, frame
    or code object. Using the real type is also what the production callers
    pass, so the test exercises the same path they do.
    """
    module = ModuleType("stub_module")
    module.__file__ = str(path)
    return module


