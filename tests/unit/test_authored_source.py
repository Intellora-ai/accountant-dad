def test_the_mutation_gate_failure_does_not_recur(tmp_path: pathlib.Path) -> None:
    """A module imported out of `mutants/` yields the AUTHORED text.

    Reproduces `test_assembly_compares_only_against_none` exactly: parse what
    the reader returns, collect every `ast.Compare` that compares against
    something other than `None`, and require the list to be empty. Against the
    instrumented file that list is `[(…, 'fail'), (…, 'stats')]` — mutmut's
    own comparisons, attributed to this repository.
    """
    authored = tmp_path / "src" / "pkg" / "thing.py"
    authored.parent.mkdir(parents=True)
    authored.write_text(AUTHORED_BODY, encoding="utf-8")

    instrumented = tmp_path / "mutants" / "src" / "pkg" / "thing.py"
    instrumented.parent.mkdir(parents=True)
    instrumented.write_text(AUTHORED_BODY + MUTMUT_DISPATCHER, encoding="utf-8")

    # What the old code did, spelled out, so the contrast is not a claim.
    running_text = instrumented.read_text(encoding="utf-8")
    running_comparisons = [
        node.lineno
        for node in ast.walk(ast.parse(running_text))
        if isinstance(node, ast.Compare)
        and not all(
            isinstance(comparator, ast.Constant) and comparator.value is None
            for comparator in node.comparators
        )
    ]
    assert running_comparisons, (
        "precondition failed: the fixture must contain the comparisons that "
        "broke the gate, otherwise this test proves nothing"
    )

    text = authored_source(_module_from(instrumented))
    comparisons = [
        node.lineno
        for node in ast.walk(ast.parse(text))
        if isinstance(node, ast.Compare)
        and not all(
            isinstance(comparator, ast.Constant) and comparator.value is None
            for comparator in node.comparators
        )
    ]
    assert comparisons == [], f"authored source still carries instrumentation at {comparisons}"
    assert "MUTANT_UNDER_TEST" not in text
    assert "'stats'" not in text


def test_no_module_in_this_package_reports_instrumented_source() -> None:
    """The invariant, asserted over every module rather than one.

    Trivially true off mutation and the entire point under it: if the redirect
    ever stops working, this goes red for thirty-three modules at once instead
    of for whichever one happens to hold a whitelist-shaped assertion.
    """
    package_root = pathlib.Path(authored_path(assembly_module)).parents[3]
    modules = sorted(package_root.rglob("*.py"))
    assert modules, f"no modules found under {package_root}; the walk is looking in the wrong place"
    marked = [
        str(path) for path in modules if "_mutmut_trampoline" in path.read_text(encoding="utf-8")
    ]
    assert marked == [], f"authored tree contains generated dispatchers: {marked}"


